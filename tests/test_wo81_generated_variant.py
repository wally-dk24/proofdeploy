"""WO-8.1 (REG-A) conformance variant: the flask golden with an
UNHASHED requirements.txt reaches READY via a GENERATED lock.

The python-flask-sqlite golden ships a fully hashed
requirements.txt (a complete committed lock). This variant swaps
in the same dependency set as ``==`` pins with NO hashes — not a
complete lock under REG-A — so provisioning must generate the
lock inside the sandbox install container: the pinned uv 0.13.0
(bootstrapped into /pd-home/.pd-tools) resolves the pins with
``--generate-hashes`` at the unit's cutoff (this single commit's
committer time) against https://pypi.org/simple, and the
generated lock installs ``--require-hashes --no-deps``. The
provision must reach READY, the canned probes must pass against
the running app, and the evidence must carry the generated lock
(text + sha256) with lock_source "generated".

Runs in the sandbox-tests CI job (PD_REQUIRE_SANDBOX), like the
forced-compile variant. Fail-before: on pre-WO-8.1 code the
==-only file is (wrongly) accepted as a lock and installed
--no-deps; the transitive closure happens to be fully pinned
here, but the plan carries no generated lock and no lock_source —
and any pin whose own dependencies are unpinned would start
without them (the WAL-76 defect).
"""
import hashlib
import os
import shutil
import socket
import subprocess
from pathlib import Path

import pytest

from conformance import kit
from proofdeploy.orchestrator import MeasureConfig, Orchestrator
from proofdeploy.probe import validate_probe

pytestmark = pytest.mark.skipif(
    not os.environ.get("PD_REQUIRE_SANDBOX"),
    reason="generated-lock variant runs in the sandbox-tests CI job",
)

APP = "python-flask-sqlite"

# The golden's dependency set as == pins with NO hashes: declared
# dependencies (constraints for the resolver), not a lock.
UNHASHED_REQUIREMENTS = (
    "flask==3.1.0\n"
    "werkzeug==3.1.3\n"
    "jinja2==3.1.4\n"
    "markupsafe==3.0.2\n"
    "click==8.1.7\n"
    "blinker==1.9.0\n"
    "itsdangerous==2.2.0\n"
)


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(repo), *args],
        check=True, capture_output=True, text=True, timeout=120,
    ).stdout.strip()


def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return int(s.getsockname()[1])


def test_unhashed_golden_ready_via_generated_lock(tmp_path):
    src = kit.GOLDEN_DIR / APP / "revisions" / "fix"
    repo = tmp_path / "repo"
    shutil.copytree(src, repo)
    # The variant: the golden's requirements WITHOUT hashes.
    (repo / "requirements.txt").write_text(
        UNHASHED_REQUIREMENTS, encoding="utf-8"
    )
    _git(repo, "init", "-q")
    _git(repo, "config", "user.name", "conformance-kit")
    _git(repo, "config", "user.email", "kit@proofdeploy.invalid")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "unhashed requirements variant")
    rev = _git(repo, "rev-parse", "HEAD")

    cfg = MeasureConfig(
        repo_dir=repo,
        output_dir=tmp_path / "records",
        workdir=tmp_path / "work",
        no_skill=True,
        sandbox=True,
    )
    orch = Orchestrator(cfg)
    unit = tmp_path / "unit"
    unit.mkdir()
    side = orch._provision_side_sandbox(
        rev, _free_port(), unit, "generated-lock"
    )
    provision = side.provision
    kit.dump_logs("wo81-generated-lock-python-flask-fix", provision.logs)
    try:
        assert provision.ready, "\n".join(provision.logs)
        plan = provision.install_plan
        assert plan is not None
        # The lock was GENERATED by the registered resolver, at a
        # cutoff, against the registered index.
        assert plan["lock_source"] == "generated", plan
        assert plan["lock_resolver"] == "uv"
        assert plan["lock_resolver_version"] == "0.13.0"
        assert plan["lock_index_url"] == "https://pypi.org/simple"
        assert plan["lock_cutoff"], plan
        # The generated lock itself is in the evidence, hashed.
        gen = provision.generated_lock
        assert gen is not None
        assert gen["sha256"] == hashlib.sha256(
            gen["text"].encode()
        ).hexdigest()
        # A generated lock is a complete hashed pin set.
        assert "--hash=sha256:" in gen["text"]
        assert "flask==3.1.0" in gen["text"]
        # The steps that ran: bootstrap, resolve, frozen install.
        installs = [
            s for s in provision.executed_steps if s["phase"] == "install"
        ]
        assert installs and all(
            s["exit_code"] == 0 for s in installs
        ), installs
        argvs = [s.get("argv_rendered") or [] for s in installs]
        # Addendum 46: the resolver was installed BY HASH from the
        # committed bootstrap requirements file (materialized into
        # {pd_tools} by the writer step), and the plan records that
        # file's sha256.
        assert any(
            any("uv==0.13.0" in el and "--hash=sha256:" in el for el in a)
            for a in argvs
        ), argvs
        boot = next(a for a in argvs if "--require-hashes" in a
                    and "--only-binary" in a)
        assert "--no-deps" in boot and ":all:" in boot
        assert plan["lock_resolver_bootstrap_sha256"], plan
        resolve = next(a for a in argvs if "compile" in a)
        assert "--generate-hashes" in resolve
        # Addendum 46: --no-header — the recorded sha256 of the
        # generated lock must not depend on the checkout path, and
        # the recorded text itself carries no autogenerated header.
        assert "--no-header" in resolve
        assert "autogenerated" not in gen["text"]
        assert resolve[resolve.index("--exclude-newer") + 1] == (
            plan["lock_cutoff"]
        )
        frozen = argvs[-1]
        assert "--require-hashes" in frozen and "--no-deps" in frozen
        # The canned probes pass against the app the generated lock
        # provisioned (register, login, read the seeded note).
        probes = kit.load_probes(APP)
        parsed = [validate_probe(probes["bug_probes"][0])]
        executor = orch._make_executor(side)
        results = executor.run_all(parsed)
        assert results and all(
            r.verdict.value == "pass" for r in results
        ), [(r.verdict, r.details) for r in results]
    finally:
        if provision.proc is not None:
            provision.proc.stop()
