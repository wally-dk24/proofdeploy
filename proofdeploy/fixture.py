"""Blind-author fixture description template and input-bundle assembler.

Implements fixture plan §2 (reviewer findings 1-2): the author-facing fixture
description is generated by script from a fixed template filled only from the
`fixture` section of proofdeploy.yml. The template is frozen and hashed before
the first author run; the bundle assembler verifies the hash fail-closed.

The author's full input bundle (diff, repo snapshot without git history,
fixture description) is assembled by script from an allowlist, never by hand.

Reviewer finding 6: snapshots are created by script via `git archive <B>`
into an empty directory; the manifest records the source SHA.
"""

from __future__ import annotations

import hashlib
import json
import os
import posixpath
import shutil
import subprocess
import tarfile
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

# Placeholders the template may contain. Anything else in {braces} fails
# closed at render time — except ${AUTH_TOKEN}, which is a runner-injected
# credential placeholder and must pass through untouched.
TEMPLATE_FIELDS = ("repo_name", "seed_note", "auth_mechanism", "auth_scope", "flags_note")

# The author's input bundle contains exactly these items, nothing else.
# skill-author.md is the generated author copy (hash 75d52a77...); the audited
# source skill.md never enters the bundle. In no-skill mode the bundle omits
# skill-author.md and the allowlist shrinks accordingly.
BUNDLE_ALLOWLIST = ("diff.patch", "snapshot", "fixture-description.txt", "skill-author.md")
BUNDLE_ALLOWLIST_NO_SKILL = ("diff.patch", "snapshot", "fixture-description.txt")

# Expected sha256 of the generated author copy. Fixed in code, not a
# parameter: the assembler verifies this fail-closed, and a different skill
# means a different measurement. Override only in tests via monkeypatch.
# Skill v5 (signed D242, docs/evaluation/o21/skill-v5-author.md): the author copy
# is byte-identical to the signed file.
EXPECTED_SKILL_HASH = "75d52a774f505dafd0ccde84cf91c9a1b8c485b2e8465e106b78d6d43268310c"

TEMPLATE_FILENAME = "fixture_template.txt"
NO_CREDENTIAL_TEMPLATE_FILENAME = "fixture_template_nocredential.txt"

# Registered sha256 of both frozen templates (REG-B registration,
# docs/registration/fixture-template-nocredential.md item 4). Any change
# to either file invalidates prior runs that used it; the answer-key
# check verifies the selected template against these values.
REGISTERED_TEMPLATE_SHA256 = {
    TEMPLATE_FILENAME: "0994d1e367ddb3c679e750451dd67eab3a3d974fc1620b7f750216cdcdf0323b",
    NO_CREDENTIAL_TEMPLATE_FILENAME: (
        "6cb8edafa3211ccd3c275648bf3a2cc5ddadbbc876aa65d8105be5186b4188e9"
    ),
}


def template_filename(declares_credential: bool) -> str:
    """REG-B item 3: the template choice is mechanical.

    A contract that declares a credential (a top-level `auth:` mapping)
    uses the credential template; any other contract uses the
    no-credential template. The choice is made before any model call,
    by the caller, from the parsed contract alone.
    """
    return TEMPLATE_FILENAME if declares_credential else NO_CREDENTIAL_TEMPLATE_FILENAME


def template_path(filename: str | None = None) -> Path:
    """Path to a frozen template file shipped with the package."""
    return Path(__file__).with_name(filename or TEMPLATE_FILENAME)


def template_hash(path: str | Path | None = None) -> str:
    """sha256 of the template file bytes (comments included)."""
    p = Path(path) if path else template_path()
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _strip_comments(text: str) -> str:
    """Remove `#` comment lines; the author never sees them."""
    lines = [ln for ln in text.splitlines() if not ln.lstrip().startswith("#")]
    return "\n".join(lines).strip() + "\n"


def render_description(template_text: str, fields: dict[str, str]) -> str:
    """Fill the template's {placeholders} from the yml fixture mapping.

    Fail-closed: every field the template uses must be present and a
    non-empty string; after substitution, any remaining {...} other than
    ${AUTH_TOKEN} raises. ${AUTH_TOKEN} passes through untouched for the
    runner to inject.

    REG-B: which fields are required follows the template. The credential
    template uses all five fields; the no-credential template has no
    {auth_scope}, so auth_scope is not required when it is used.
    """
    body = _strip_comments(template_text)
    # Protect the runner placeholder from brace scanning, then restore it.
    sentinel = "\x00AUTH_TOKEN\x00"
    body = body.replace("${AUTH_TOKEN}", sentinel)
    used = [f for f in TEMPLATE_FIELDS if "{" + f + "}" in body]
    missing = [f for f in used if not fields.get(f)]
    if missing:
        raise ValueError(f"fixture mapping missing fields: {', '.join(missing)}")
    for f in used:
        if not isinstance(fields[f], str):
            raise ValueError(f"fixture field '{f}' must be a string")
    for f in used:
        body = body.replace("{" + f + "}", fields[f])
    if "{" in body or "}" in body:
        raise ValueError(
            "template contains an unknown {placeholder}: only the five fixture fields are allowed"
        )
    return body.replace(sentinel, "${AUTH_TOKEN}")


@dataclass
class AuthorBundle:
    """Paths of an assembled author input bundle."""

    root: Path
    diff: Path
    snapshot: Path
    description: Path
    manifest: Path
    skill: Path | None = None  # None in no-skill (baseline) mode


def _sha256_file(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


# ---------------------------------------------------------------------------
# Symlink handling (WO-8.4b; Master's decision, docs/adr/0012).
#
# 1. A symlink in a snapshot is kept only if its target is relative and
#    resolves inside the snapshot tree.
# 2. Anything else is refused, with a typed reason naming the path. That
#    covers absolute targets and targets that escape the tree through
#    `..` or chained links.
# 3. The probe author's bundle never follows links: link entries are
#    omitted from the bundle entirely and recorded in the manifest.
# ---------------------------------------------------------------------------

# Typed refusal reasons for snapshot symlinks (WO-8.4b rule 2).
LINK_TARGET_ABSOLUTE = "symlink-target-absolute"
LINK_TARGET_ESCAPES = "symlink-target-escapes-tree"
LINK_RESOLUTION_LOOP = "symlink-resolution-loop"

_MAX_LINK_HOPS = 40


class SnapshotLinkError(ValueError):
    """A snapshot symlink fails the WO-8.4b rule: typed reason + the path."""

    def __init__(self, path: str, target: str, reason: str) -> None:
        self.path = path
        self.target = target
        self.reason = reason
        super().__init__(f"snapshot symlink refused ({reason}): {path} -> {target}")


def _resolve_link_target(
    links: dict[str, str], link_rel: str, target: str
) -> tuple[list[str] | None, str | None]:
    """Resolve ``target`` component-wise over the tree's symlink map.

    ``links`` maps posix relative paths to their target strings. Returns
    ``(parts, None)`` with the final path's components — every component
    real, symlink components substituted eagerly exactly as the kernel
    resolves them, so the result is inside the tree by construction —
    or ``(None, reason)`` when the target is absolute, escapes the
    tree, or chains past the hop cap. The decision never touches the
    filesystem, so it is identical for a tar stream mid-extraction and
    for a materialized tree.
    """
    if posixpath.isabs(target):
        return None, LINK_TARGET_ABSOLUTE
    parts: list[str] = link_rel.split("/")[:-1]  # the link's own directory
    todo: list[str] = target.split("/")
    hops = 0
    while todo:
        comp = todo.pop(0)
        if comp in ("", "."):
            continue
        if comp == "..":
            if not parts:
                return None, LINK_TARGET_ESCAPES
            parts.pop()
            continue
        parts.append(comp)
        cur = "/".join(parts)
        if cur in links:
            hops += 1
            if hops > _MAX_LINK_HOPS:
                return None, LINK_RESOLUTION_LOOP
            hop_target = links[cur]
            if posixpath.isabs(hop_target):
                return None, LINK_TARGET_ABSOLUTE
            parts.pop()  # substitute the link component with its target
            todo = hop_target.split("/") + todo
    return parts, None


def _validate_snapshot_link(links: dict[str, str], link_rel: str) -> None:
    """Raise SnapshotLinkError unless the link obeys WO-8.4b rule 1."""
    _parts, reason = _resolve_link_target(links, link_rel, links[link_rel])
    if reason is not None:
        raise SnapshotLinkError(link_rel, links[link_rel], reason)


def _scan_snapshot_tree(snap: Path) -> tuple[list[Path], list[Path], dict[str, str]]:
    """Enumerate a snapshot tree without ever following a link.

    Returns ``(dirs, files, links)``: real directories and regular
    files as paths, and the symlink map ``{posix rel path: target}``.
    Refuses `.git` at any depth (a submodule or vendored checkout can
    carry history in a nested `.git`) and any symlink failing the
    WO-8.4b rule (SnapshotLinkError naming the path).
    """
    dirs: list[Path] = []
    files: list[Path] = []
    links: dict[str, str] = {}
    for dirpath, dirnames, filenames in os.walk(snap, followlinks=False):
        base = Path(dirpath)
        for name in list(dirnames):
            p = base / name
            if name == ".git":
                raise ValueError(f"snapshot must not contain .git history: {p}")
            if p.is_symlink():
                links[p.relative_to(snap).as_posix()] = os.readlink(p)
                dirnames.remove(name)  # never descend through a link
            else:
                dirs.append(p)
        for name in filenames:
            p = base / name
            if name == ".git":
                raise ValueError(f"snapshot must not contain .git history: {p}")
            if p.is_symlink():
                links[p.relative_to(snap).as_posix()] = os.readlink(p)
            else:
                files.append(p)
    for rel in sorted(links):
        _validate_snapshot_link(links, rel)
    return dirs, files, links


def _tree_hash(root: Path) -> str:
    """Deterministic hash of a directory tree.

    sha256 over each file's sorted relative posix path plus its content
    hash, so the manifest records exactly which snapshot went into the
    bundle.
    """
    h = hashlib.sha256()
    files = sorted(p for p in root.rglob("*") if p.is_file() and not p.is_symlink())
    for p in files:
        h.update(p.relative_to(root).as_posix().encode() + b"\x00")
        h.update(_sha256_file(p).encode() + b"\x00")
    h.update(f"{len(files)} files".encode())
    return h.hexdigest()


def _check_output_dir(out: Path) -> None:
    """The bundle directory must be empty (or absent) before assembly.

    Anything already in the output directory would otherwise ride along
    into the author's bundle outside the allowlist.
    """
    if out.exists() and not out.is_dir():
        raise ValueError(f"output path exists and is not a directory: {out}")
    if out.exists() and any(out.iterdir()):
        raise ValueError(f"output directory is not empty: {out}; assemble into an empty directory")


@dataclass
class Snapshot:
    """A repo snapshot created by script from a git commit."""

    dir: Path
    sha: str  # full resolved commit SHA; recorded as the manifest's source_sha


def _git(repo_dir: Path, *args: str) -> subprocess.CompletedProcess[bytes]:
    """Run git in repo_dir, returning the completed process (never raising)."""
    return subprocess.run(
        ["git", "-C", str(repo_dir), *args],
        capture_output=True,
        check=False,
    )


def tree_gitlinks(repo_dir: str | Path, rev: str) -> dict[str, str]:
    """{path: pinned commit} for every gitlink (mode 160000) in rev's tree.

    Derived from ``git ls-tree -r`` on the commit itself. The measured
    path passes this to `assemble_author_bundle` for the manifest's
    ``omitted_gitlinks`` record (D143); the answer-key check recomputes
    the same set from B independently and cross-verifies the record —
    it is never trusted from the manifest.
    """
    proc = _git(Path(repo_dir), "ls-tree", "-r", "-z", rev)
    if proc.returncode != 0:
        raise ValueError(
            f"git ls-tree {rev} failed in {repo_dir}: "
            f"{proc.stderr.decode('utf-8', 'replace').strip()}"
        )
    gitlinks: dict[str, str] = {}
    for entry in proc.stdout.decode("utf-8", "surrogateescape").split("\x00"):
        if not entry:
            continue
        meta, _, path = entry.partition("\t")
        parts = meta.split(" ")
        if len(parts) == 3 and parts[0] == "160000":
            gitlinks[path] = parts[2]
    return gitlinks


def create_snapshot(
    *,
    repo_dir: str | Path,
    commit_rev: str,
    output_dir: str | Path,
) -> Snapshot:
    """Create a repo snapshot at <commit_rev> via `git archive`.

    Resolves <commit_rev> to its full SHA with `git rev-parse`, then streams
    `git archive <sha>` out of repo_dir and extracts it into output_dir,
    which must be absent or empty (fail closed). `git archive` emits file
    contents only — no history, no `.git` directory — so there is nothing
    to smuggle by construction.

    The archive streams through a pipe (never fully buffered in memory) and
    each member is validated before extraction: hardlinks and
    non-file/non-dir members are refused outright, and any member whose
    path would escape output_dir raises. Symlink members are DEFERRED
    until every file is extracted, then validated against the WO-8.4b
    rule (target relative and resolving inside the tree, chains
    included) and created as symlinks; a symlink failing the rule
    raises SnapshotLinkError with a typed reason naming the path.

    Returns the snapshot directory and the resolved full SHA. Pass the SHA
    as `source_sha` to `assemble_author_bundle` so the manifest records
    exactly which commit the snapshot came from.

    Fail-closed: unknown rev, non-empty output dir, `git archive` failure,
    a hardlink or escaping archive member, or a symlink member failing
    the WO-8.4b rule all raise.
    """
    repo = Path(repo_dir)
    out = Path(output_dir)

    rev = _git(repo, "rev-parse", "--verify", f"{commit_rev}^{{commit}}")
    if rev.returncode != 0:
        raise ValueError(
            f"cannot resolve commit {commit_rev!r} in {repo}: {rev.stderr.decode().strip()}"
        )
    sha = rev.stdout.decode().strip()

    _check_output_dir(out)
    out.mkdir(parents=True, exist_ok=True)

    out_resolved = out.resolve()
    proc = subprocess.Popen(
        ["git", "-C", str(repo), "archive", sha],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    stderr = b""
    links: dict[str, str] = {}
    try:
        assert proc.stdout is not None  # for mypy: Popen with PIPE sets it
        with tarfile.open(fileobj=proc.stdout, mode="r|") as tf:
            for member in tf:
                if member.islnk():
                    raise ValueError(f"archive member is a hardlink, refused: {member.name}")
                if not (member.isfile() or member.isdir() or member.issym()):
                    raise ValueError(f"archive member is not a file or dir, refused: {member.name}")
                target = (out / member.name).resolve()
                if not str(target).startswith(str(out_resolved) + "/"):
                    raise ValueError(f"archive member escapes snapshot dir: {member.name}")
                if member.issym():
                    # Deferred: no link exists on disk during extraction,
                    # so the resolve() above stays purely lexical, and the
                    # chain check sees the archive's complete link map.
                    links[posixpath.normpath(member.name)] = member.linkname
                    continue
                tf.extract(member, out)
    except Exception:
        # Validation failed mid-stream: the producer may be blocked writing
        # to the pipe we stopped reading, so stop it before reaping.
        if proc.poll() is None:
            proc.kill()
        _, stderr = proc.communicate()
        raise
    # The stream is fully consumed; the producer is exiting on its own.
    # Reap it without killing: killing here races the producer's exit and
    # turns a healthy run into returncode -9 (empty stderr).
    try:
        _, stderr = proc.communicate(timeout=60)
    except subprocess.TimeoutExpired:
        proc.kill()
        _, stderr = proc.communicate()
    if proc.returncode != 0:
        raise ValueError(f"git archive {sha} failed in {repo}: {stderr.decode().strip()}")
    # Every file is extracted and the producer reaped clean: validate
    # the deferred symlinks against the WO-8.4b rule (all-or-nothing —
    # validate the whole map before creating any link), then create
    # them with their target strings verbatim.
    for rel in sorted(links):
        _validate_snapshot_link(links, rel)
    for rel in sorted(links):
        os.symlink(links[rel], out / rel)
    return Snapshot(dir=out, sha=sha)


def _check_bundle_contents(out: Path, allowlist: tuple[str, ...]) -> None:
    """After assembly the bundle must contain exactly the allowlist."""
    actual = sorted(p.name for p in out.iterdir())
    if actual != sorted(allowlist):
        raise ValueError(
            f"bundle contents {actual} do not match the allowlist {sorted(allowlist)}"
        )


def assemble_author_bundle(
    *,
    diff_path: str | Path,
    snapshot_dir: str | Path,
    yml_fixture: dict[str, str],
    output_dir: str | Path,
    expected_template_hash: str,
    template_file: str | Path | None = None,
    source_sha: str | None = None,
    diff_range: str | None = None,
    skill_path: str | Path | None = None,
    no_skill: bool = False,
    gitlinks: dict[str, str] | None = None,
) -> AuthorBundle:
    """Assemble the blind author's input bundle from the allowlist.

    Verifies the frozen template hash before rendering (fail closed), renders
    the fixture description from the yml fixture mapping, copies the diff,
    the snapshot, and (unless no_skill) the generated author skill copy, and
    writes a manifest NEXT TO the bundle (never inside it — the manifest may
    record source SHAs and diff ranges that must not reach the author).

    The skill hash is verified fail-closed against EXPECTED_SKILL_HASH (fixed
    in code) and recorded in the manifest, so every run is tied to exactly
    the registered skill content. In no_skill mode (the baseline arm), the
    bundle omits skill-author.md and the manifest records no skill hash.

    REG-B: the caller selects the template mechanically from the contract
    (see template_filename) and identifies it via template_file +
    expected_template_hash; the manifest records the selection as
    fixture_template {file, sha256} so the answer-key check can recompute
    it from the contract and refuse a mismatch.

    WO-8.4b rule 3: the bundle never follows links. Link entries in the
    snapshot are omitted from the bundle copy entirely — no content
    reaches the author through a link — and each omitted link is
    recorded in the manifest as its path and target string
    (`omitted_links`). A snapshot symlink failing rule 1/2 (absolute,
    escaping, or looping target) refuses assembly outright
    (SnapshotLinkError naming the path).

    D143: the source tree's gitlinks (submodule entries, mode 160000)
    are passed in as `gitlinks` ({path: pinned commit}, derived from
    the tree by the caller — see `tree_gitlinks`) and recorded in the
    manifest as `omitted_gitlinks`. `git archive` carries no submodule
    contents — a gitlink arrives in the snapshot as an empty directory
    and holds no files — so, like an omitted link, the omission is
    what the record attests; the answer-key check re-derives the set
    from B and cross-verifies path and commit. Assembly refuses if a
    declared gitlink path is not a directory in the snapshot or if any
    file sits at or under it (submodule contents never enter the
    bundle; D46 materialisation stays on the provisioning path).

    Fail-closed throughout: template hash mismatch, skill hash mismatch,
    non-empty output dir, `.git` at any depth in the snapshot, a symlink
    failing the WO-8.4b rule, or a final bundle whose contents differ
    from the allowlist all raise.
    """
    tpath = Path(template_file) if template_file else template_path()
    actual_hash = hashlib.sha256(tpath.read_bytes()).hexdigest()
    if actual_hash != expected_template_hash:
        raise ValueError(
            "template hash mismatch: the frozen template changed; prior author runs are invalidated"
        )

    diff_p = Path(diff_path)
    snap_p = Path(snapshot_dir)
    out = Path(output_dir)
    if not diff_p.is_file():
        raise ValueError(f"diff not found: {diff_p}")
    if not snap_p.is_dir():
        raise ValueError(f"snapshot dir not found: {snap_p}")
    snap_dirs, snap_files, snap_links = _scan_snapshot_tree(snap_p)
    gitlink_map: dict[str, str] = dict(gitlinks) if gitlinks else {}
    if gitlink_map:
        # D143: a declared gitlink must be exactly what `git archive`
        # delivers — an empty directory. A missing path, or any file
        # at or under the path, means the snapshot is not the archive
        # of the tree the gitlinks were derived from: refuse.
        snap_dir_set = {d.relative_to(snap_p).as_posix() for d in snap_dirs}
        snap_file_set = {f.relative_to(snap_p).as_posix() for f in snap_files}
        for rel in sorted(gitlink_map):
            if rel not in snap_dir_set:
                raise ValueError(
                    f"gitlink path is not a directory in the snapshot: {rel}"
                )
            under = sorted(
                f for f in snap_file_set if f == rel or f.startswith(rel + "/")
            )
            if under:
                raise ValueError(
                    f"snapshot holds files under gitlink path {rel}: "
                    f"{under[:5]}; submodule contents never enter the bundle"
                )
    _check_output_dir(out)

    description = render_description(tpath.read_text(encoding="utf-8"), yml_fixture)

    out.mkdir(parents=True, exist_ok=True)
    out_diff = out / "diff.patch"
    out_snap = out / "snapshot"
    out_desc = out / "fixture-description.txt"
    out_skill = out / "skill-author.md"
    shutil.copyfile(diff_p, out_diff)
    # Copy the snapshot file-by-file from the scan: directories and
    # regular files only. Link entries are omitted entirely (WO-8.4b
    # rule 3) — copytree is not used because it would follow links and
    # copy target content into the bundle. Re-scan the copy belt and
    # braces: it must hold exactly the scanned files and no links.
    out_snap.mkdir(parents=True, exist_ok=True)
    for d in snap_dirs:
        (out_snap / d.relative_to(snap_p)).mkdir(parents=True, exist_ok=True)
    for f in snap_files:
        shutil.copy2(f, out_snap / f.relative_to(snap_p))
    _copy_dirs, copy_files, copy_links = _scan_snapshot_tree(out_snap)
    if copy_links or len(copy_files) != len(snap_files):
        raise ValueError("bundle snapshot copy does not match the scanned source tree")
    out_desc.write_text(description, encoding="utf-8")

    # The generated author copy goes in the bundle; its hash is verified
    # fail-closed against EXPECTED_SKILL_HASH (fixed in code) and recorded
    # in the manifest. The audited source never enters the bundle.
    # In no_skill mode (baseline arm), the skill is omitted entirely.
    allowlist: tuple[str, ...] = BUNDLE_ALLOWLIST
    skill_hash: str | None = None
    if no_skill:
        allowlist = BUNDLE_ALLOWLIST_NO_SKILL
        if out_skill.exists():
            out_skill.unlink()
    else:
        if skill_path is None:
            raise ValueError(
                "skill_path is required (or pass no_skill=True for the baseline arm)"
            )
        skill_p = Path(skill_path)
        if not skill_p.is_file():
            raise ValueError(f"skill file not found: {skill_p}")
        skill_hash = _sha256_file(skill_p)
        if skill_hash != EXPECTED_SKILL_HASH:
            raise ValueError(
                "skill hash mismatch: expected the registered author copy; "
                "a different skill means a different measurement"
            )
        shutil.copyfile(skill_p, out_skill)

    _check_bundle_contents(out, allowlist)

    manifest: dict[str, Any] = {
        "assembled_at": datetime.now(timezone.utc).isoformat(),
        "template_sha256": actual_hash,
        "fixture_template": {"file": tpath.name, "sha256": actual_hash},
        "allowlist": list(allowlist),
        "snapshot_tree_sha256": _tree_hash(out_snap),
        # WO-8.4b rule 3: every link omitted from the bundle, recorded
        # as its path and its target string. The manifest sits next to
        # the bundle, never inside it, so this reaches no author.
        "omitted_links": [
            {"path": rel, "target": snap_links[rel]} for rel in sorted(snap_links)
        ],
        # D143: every gitlink of the source tree, recorded as its path
        # and pinned commit. `git archive` delivers the path as an
        # empty directory with no contents, so the bundle omits the
        # submodule by construction; the record lets the answer-key
        # check verify the omission against B. The manifest sits next
        # to the bundle, never inside it, so this reaches no author.
        "omitted_gitlinks": [
            {"path": rel, "commit": gitlink_map[rel]} for rel in sorted(gitlink_map)
        ],
        "files": {
            "diff.patch": _sha256_file(out_diff),
            "fixture-description.txt": _sha256_file(out_desc),
        },
    }
    if skill_hash is not None:
        manifest["skill_sha256"] = skill_hash
        manifest["files"]["skill-author.md"] = skill_hash
    else:
        manifest["skill_sha256"] = None  # no-skill baseline arm
    # Source SHAs and diff ranges live in the manifest, which sits next to
    # the bundle — never inside it, never reaching the author.
    if source_sha is not None:
        manifest["source_sha"] = source_sha
    if diff_range is not None:
        manifest["diff_range"] = diff_range
    out_manifest = out.with_name(out.name + ".manifest.json")
    out_manifest.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return AuthorBundle(
        root=out,
        diff=out_diff,
        snapshot=out_snap,
        description=out_desc,
        skill=None if no_skill else out_skill,
        manifest=out_manifest,
    )
